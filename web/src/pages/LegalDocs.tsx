function LegalDocument({ doc }: { doc: LegalDoc }) {
  return (
    <div className="section legal-page">
      <div className="pageBackRow">
        <PageBackButton to="/profile" />
      </div>
      <LegalHero />
      <LegalTabs active={doc.key} />

      <div className="card legal-document-hero">
        <div className="card__body">
          <div className="legal-document-hero__head">
            <div className="legal-document-hero__icon"><LegalIcon name={doc.key} /></div>
            <div>
              <h2 className="legal-title">{doc.title}</h2>
              <p className="p">{doc.description}</p>
              <div className="legal-meta">Редакция от {EDITION_DATE}</div>
            </div>
          </div>
        </div>
      </div>

      <nav className="legal-toc" aria-label="Содержание документа">
        <span className="legal-toc__label">Содержание</span>
        <div className="legal-toc__links">
          {doc.sections.map((section, index) => (
            <a
              key={section.title}
              className="legal-toc__link"
              href={`#legal-${doc.key}-${index}`}
              onClick={(event) => {
                event.preventDefault();
                document.getElementById(`legal-${doc.key}-${index}`)?.scrollIntoView({ behavior: "smooth", block: "start" });
              }}
            >
              {section.title}
            </a>
          ))}
        </div>
      </nav>

      <div className="legal-doc-sections">
        {doc.sections.map((section, index) => (
          <section className="card legal-section-card" key={section.title} id={`legal-${doc.key}-${index}`}>
            <div className="card__body">
              <h3 className="legal-section-title">{section.title}</h3>
              {section.body?.map((paragraph) => {
                if (paragraph.startsWith("Telegram:")) {
                  return (
                    <p className="legal-p" key={paragraph}>
                      Telegram: <a href={SUPPORT_TELEGRAM} target="_blank" rel="noopener noreferrer">@shpun_staff</a>
                    </p>
                  );
                }
                if (paragraph.startsWith("Email:")) {
                  return (
                    <p className="legal-p" key={paragraph}>
                      Email: <a href={`mailto:${SUPPORT_EMAIL}`}>{SUPPORT_EMAIL}</a>
                    </p>
                  );
                }
                return <p className="legal-p" key={paragraph}>{paragraph}</p>;
              })}
              {section.list ? (
                <ul className="legal-list">
                  {section.list.map((item) => <li key={item}>{item}</li>)}
                </ul>
              ) : null}
              {section.callout ? <div className="legal-callout">{section.callout}</div> : null}
              {section.faq ? (
                <div className="legal-faq">
                  {section.faq.map((item) => (
                    <div className="legal-faq__item" key={item.q}>
                      <div className="legal-faq__q">{item.q}</div>
                      <div className="legal-faq__a">{item.a}</div>
                    </div>
                  ))}
                </div>
              ) : null}
            </div>
          </section>
        ))}
      </div>
    </div>
  );
}

export function LegalDocs() {
  const { docKey } = useParams();

  if (!docKey) return <LegalOverview />;

  const doc = getDoc(docKey);
  if (!doc) return <Navigate to="/legal" replace />;

  return <LegalDocument doc={doc} />;
}

export default LegalDocs;
